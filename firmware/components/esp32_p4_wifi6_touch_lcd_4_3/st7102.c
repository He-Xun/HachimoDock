static esp_err_t st7102_reset(esp_lcd_panel_t *panel)
{
    st7102_panel_t *st = panel->user_data;
    ESP_RETURN_ON_ERROR(esp_lcd_panel_io_tx_param(st->io, LCD_CMD_SWRESET, NULL, 0),
                        TAG, "Software reset failed");
    vTaskDelay(pdMS_TO_TICKS(120));
    return ESP_OK;
}

static esp_err_t st7102_init(esp_lcd_panel_t *panel)
{
    st7102_panel_t *st = panel->user_data;
    for (size_t i = 0; i < sizeof(init_commands) / sizeof(init_commands[0]); ++i) {
        ESP_RETURN_ON_ERROR(esp_lcd_panel_io_tx_param(st->io, init_commands[i].command,
                            init_commands[i].data, init_commands[i].size), TAG,
                            "Command 0x%02x failed", init_commands[i].command);
        if (init_commands[i].delay_ms) vTaskDelay(pdMS_TO_TICKS(init_commands[i].delay_ms));
    }
    return st->dpi_init(panel);
}

static esp_err_t st7102_disp_on_off(esp_lcd_panel_t *panel, bool on)
{
    st7102_panel_t *st = panel->user_data;
    return esp_lcd_panel_io_tx_param(st->io, on ? LCD_CMD_DISPON : LCD_CMD_DISPOFF, NULL, 0);
}

static esp_err_t st7102_del(esp_lcd_panel_t *panel)
{
    st7102_panel_t *st = panel->user_data;
    esp_err_t err = st->dpi_del(panel);
    if (err == ESP_OK) free(st);
    return err;
}

esp_err_t bsp_new_st7102_panel(esp_lcd_dsi_bus_handle_t bus, esp_lcd_panel_io_handle_t io,
                               const esp_lcd_dpi_panel_config_t *config, esp_lcd_panel_handle_t *panel)
{
    st7102_panel_t *st = calloc(1, sizeof(*st));
    if (!st) return ESP_ERR_NO_MEM;
    esp_err_t err = esp_lcd_new_panel_dpi(bus, config, panel);
    if (err != ESP_OK) {
        free(st);
        return err;
    }
    st->io = io;
    st->dpi_init = (*panel)->init;
    st->dpi_del = (*panel)->del;
    (*panel)->user_data = st;
    (*panel)->init = st7102_init;
    (*panel)->del = st7102_del;
    (*panel)->reset = st7102_reset;
    (*panel)->disp_on_off = st7102_disp_on_off;
    return ESP_OK;
}
